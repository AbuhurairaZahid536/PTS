/*
|--------------------------------------------------------------------------
| DEEP MERGE
|--------------------------------------------------------------------------
|
| Empty arrays are respected.
| Missing values fallback to defaults.
|
|--------------------------------------------------------------------------
*/

export function mergePublicSiteContent(
  incoming
) {
  const merge =
    (
      base,
      source
    ) => {
      if (
        source ===
        undefined
      ) {
        return structuredCloneFallback(
          base
        );
      }

      if (
        Array.isArray(
          source
        )
      ) {
        return structuredCloneFallback(
          source
        );
      }

      if (
        source &&
        typeof source ===
          "object" &&
        !Array.isArray(
          source
        )
      ) {
        const result =
          {};

        const keys =
          new Set([
            ...Object.keys(
              base ||
              {}
            ),

            ...Object.keys(
              source
            ),
          ]);


        keys.forEach(
          (
            key
          ) => {
            result[
              key
            ] =
              merge(
                base?.[
                  key
                ],
                source[
                  key
                ]
              );
          }
        );


        return result;
      }

      return source;
    };


  return merge(
    DEFAULT_PUBLIC_SITE_CONTENT,
    incoming ||
      {}
  );
}


export function structuredCloneFallback(
  value
) {
  return JSON.parse(
    JSON.stringify(
      value
    )
  );
}